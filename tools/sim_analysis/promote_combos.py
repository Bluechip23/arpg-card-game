#!/usr/bin/env python3
"""Promote the 3b sweep's top positive synergies into the planner's registry.

Reads sim_out/charts/combos.csv (written by combos.py) and sim_out/catalog.json,
takes the top --count (20) pairs with synergy > 0, orders each pair setup-first
(a card that deals no damage, or whose text applies an amp / control / armor
strip / buff, is the setup; the hitter is the payoff), and writes
tests/sim/combos_promoted.gd. With no positive pair the file is written empty.
With --csv the pairs come from another sweep's table in the same shape — the
deck-pair ablation (deck_pairs.py → <char>_deck_pairs.csv), where a `build`
column says which deck showed the pair; --min-share keeps only pairs whose
synergy is at least that share of the deck's DPT, and --resolved only those
that cleared their own seed noise (the table's `resolved` column).
Usage: python3 tools/sim_analysis/promote_combos.py [--count 20] [--csv path] [--min-share 0.15] [--resolved]
"""
import argparse
import json
import os

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSV = os.path.join(ROOT, "sim_out", "charts", "combos.csv")
CATALOG = os.path.join(ROOT, "sim_out", "catalog.json")
OUT = os.path.join(ROOT, "tests", "sim", "combos_promoted.gd")
SETUP_WORDS = ["vulnerable", "weaken", "expose", "stun", "root", "freeze", "disarm", "silence", "trip",
               "remove", "armor", "next attack", "strengthen", "empower", "mark", "poison"]


def is_setup(card):
    text = (card.get("description") or "").lower()
    return card.get("damage", 0) <= 0 or any(w in text for w in SETUP_WORDS)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--count", type=int, default=20)
    ap.add_argument("--csv", default=CSV, help="pair table to promote from (default: the 3b combos.csv)")
    ap.add_argument("--min-share", type=float, default=0.0, help="synergy / base_dpt a pair needs (0 = any positive)")
    ap.add_argument("--resolved", action="store_true", help="only pairs the table marks resolved (beyond 2 s.e.)")
    args = ap.parse_args()
    csv_path = args.csv
    by_id = {}
    scored = 0
    rows = []
    if os.path.exists(CATALOG):
        by_id = {c["id"]: c for c in json.load(open(CATALOG))["cards"]}
    if os.path.exists(csv_path):
        df = pd.read_csv(csv_path)
        scored = len(df)
        pos = df[df["synergy"] > 0]
        if args.min_share > 0:
            pos = pos[pos["synergy"] >= args.min_share * pos["base_dpt"]]
        if args.resolved and "resolved" in pos:
            pos = pos[pos["resolved"].astype(bool)]
        pos = pos.sort_values("synergy", ascending=False)
        if "build" in pos:
            # One entry per pair: the same two cards in two decks is one combo.
            pos = pos.drop_duplicates(subset=["pair"], keep="first")
        pos = pos.head(args.count)
        for _, r in pos.iterrows():
            a, b = r["pair"].split("+", 1)
            ca, cb = by_id.get(a, {}), by_id.get(b, {})
            cards = [a, b] if is_setup(ca) and not is_setup(cb) else ([b, a] if is_setup(cb) and not is_setup(ca) else sorted([a, b]))
            pre = {"min_mana": int(ca.get("mana", 0)) + int(cb.get("mana", 0))}
            if "enemy" in str(ca.get("description", "")).lower() + str(cb.get("description", "")).lower():
                pre["target"] = "enemy"
            rid = r["pair"] if "build" not in r else "%s@%s" % (r["pair"], r["build"])
            rows.append({"id": rid, "cards": cards, "preconditions": pre, "payoff": round(float(r["synergy"]) * 5.0, 2)})
    lines = ["extends RefCounted", "",
             "## GENERATED by tools/sim_analysis/promote_combos.py from the 3b combo sweep",
             "## (%s): the top %d POSITIVE synergies, promoted into" % (os.path.relpath(csv_path, ROOT), args.count),
             "## the planner's registry. Do not hand-edit — re-run the promoter.",
             "##",
             "## Source: %s (%d pairs scored, %d promoted%s)." % (os.path.relpath(csv_path, ROOT), scored, len(rows),
                                                                  (", min share %.2f" % args.min_share) if args.min_share > 0 else "")]
    if not rows:
        lines += ["## Nothing qualified: no scored pair is positive past the bar set for it",
                  "## (any positive by default; --min-share / --resolved raise it), so the",
                  "## registry is empty and the planner runs unaided.",
                  "const ENTRIES := []"]
    else:
        lines.append("const ENTRIES := [")
        for r in rows:
            lines.append('\t{"id": "%s", "cards": %s, "preconditions": %s, "payoff": %.2f},'
                         % (r["id"], json.dumps(r["cards"]), json.dumps(r["preconditions"]), r["payoff"]))
        lines.append("]")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d entr%s (%d pairs scored)" % (os.path.relpath(OUT, ROOT), len(rows), "y" if len(rows) == 1 else "ies", scored))


if __name__ == "__main__":
    main()
