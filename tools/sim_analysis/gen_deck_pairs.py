#!/usr/bin/env python3
"""3b on a designed deck: which pairs of the deck's own cards pay together?

A deck-pair ablation. For each designed build the deck runs whole, with one
copy of each distinct card swapped for an inert blank (`blank_cards=`; the
deck keeps its size and, per seed, its shuffle — `--mode remove` takes the
card out instead, which changes both and confounds the reading), and with
one copy of each pair swapped; the analysis (deck_pairs.py) reads

    synergy(a, b) = DPT(deck) - DPT(deck - a) - DPT(deck - b) + DPT(deck - a - b)

per enemy and averages. Positive: the two are worth more together than apart
(a setup and its payoff); negative: they compete for the same bar. No
opening-hand spotlight (every variant is the deck as drawn), so the fights
want to run long enough for the deck to turn over — pick enemies the build
beats in several bars, not in one.

Usage: python3 tools/sim_analysis/gen_deck_pairs.py --character ryan --level 18
         [--builds a,b] [--enemies ARMORED_TROLL,WYVERN,BONE_DRAGON]
         [--policy combo_planner] [--seeds 30]
Writes tests/sim/sweeps/<char>_deck_pairs.txt; run it with run_sweep.sh and
read it with deck_pairs.py.
"""
import argparse
import itertools
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SCENARIO = "tests/sim/scenarios/build.gd"


def read_gd_dict(path, name):
    """The DECKS / BUILDS literals from a builds .gd file, without Godot."""
    src = open(os.path.join(ROOT, path)).read()
    m = re.search(r"const %s\s*:?=\s*\{(.*?)\n\}" % name, src, re.S)
    if not m:
        raise SystemExit("no %s in %s" % (name, path))
    body = m.group(1)
    out = {}
    for key, val in re.findall(r'"([a-z_]+)"\s*:\s*(\[[^\]]*\]|\{[^}]*\})', body):
        out[key] = val
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--character", default="ryan")
    ap.add_argument("--level", type=int, default=18)
    ap.add_argument("--builds", default="", help="comma-separated designed builds (default: all)")
    ap.add_argument("--enemies", default="ARMORED_TROLL,WYVERN,BONE_DRAGON")
    ap.add_argument("--policy", default="combo_planner")
    ap.add_argument("--seeds", type=int, default=30)
    ap.add_argument("--mode", choices=["blank", "remove"], default="blank", help="blank: swap for sim_blank (default); remove: take the card out")
    ap.add_argument("--out", default=os.path.join(ROOT, "tests", "sim", "sweeps"))
    args = ap.parse_args()
    char = args.character
    builds = read_gd_dict("tests/sim/builds/%s_builds.gd" % char, "DESIGNED")
    decks = read_gd_dict("tests/sim/builds/decks.gd", "DECKS")
    deck_of = {}
    for b, lit in builds.items():
        m = re.search(r'"deck"\s*:\s*"([a-z_]+)"', lit)
        if m:
            deck_of[b] = m.group(1)
    wanted = [b for b in args.builds.split(",") if b] or sorted(deck_of)
    enemies = [e for e in args.enemies.split(",") if e]
    seeds = "seeds=1-%d" % args.seeds
    lines = []
    for b in wanted:
        if b not in deck_of:
            raise SystemExit("%s has no deck in %s_builds.gd" % (b, char))
        cards = re.findall(r'"([a-z_]+)"', decks[deck_of[b]])
        distinct = sorted(set(cards))
        parts = "character:%s,build:%s,level:%d" % (char, b, args.level)

        key = "blank_cards" if args.mode == "blank" else "remove_cards"
        tagc = "b" if args.mode == "blank" else "m"

        def job(enemy, remove, tag):
            rm = (" %s=%s" % (key, ",".join(remove))) if remove else ""
            return "scenario=%s policy=%s enemy=%s parts=%s%s name=e_%s__d_%s %s" % (
                SCENARIO, args.policy, enemy, parts, rm, enemy, tag, seeds)

        for e in enemies:
            lines.append(job(e, [], "full"))
            for a in distinct:
                lines.append(job(e, [a], tagc + "-" + a))
            for a, c in itertools.combinations(distinct, 2):
                lines.append(job(e, [a, c], "%s-%s+%s" % (tagc, a, c)))
    path = os.path.join(args.out, "%s_deck_pairs.txt" % char)
    with open(path, "w") as f:
        f.write("# %s deck-pair ablation on the designed decks (%s, %d seeds, mode %s): full deck, one card %s, a pair %s\n"
                % (char, args.policy, args.seeds, args.mode, "blanked" if args.mode == "blank" else "removed", "blanked" if args.mode == "blank" else "removed"))
        f.write("# generated by tools/sim_analysis/gen_deck_pairs.py --character %s --level %d --enemies %s; %d job(s)\n" % (char, args.level, args.enemies, len(lines)))
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d job(s)" % (path, len(lines)))


if __name__ == "__main__":
    main()
